func TestRender_GeneratesAndCachesDerivative(t *testing.T) {
	st := newFakeStorage()
	svc := newTestService(st)
	m := createMaster(t, svc, "acme", "t1")
	opts := imageprocessing.ResizeOptions{Width: 50, Height: 50, Mode: imageprocessing.ResizeModeExact}

	data, ct, err := svc.Render(context.Background(), "acme", "t1", m.ID, opts, "")
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if ct != "image/jpeg" {
		t.Errorf("content type = %s", ct)
	}
	if w, h := decodeDims(t, data); w != 50 || h != 50 {
		t.Errorf("derivative is %dx%d", w, h)
	}
	if !st.has(derivativeKey("acme", "t1", m.ID, 50, 50, "exact", "jpg")) {
		t.Errorf("derivative not cached; keys=%v", st.keys())
	}

	// Second request must be served from cache: no new upload, master not re-read.
	uploads, downloads := st.uploads, st.downloads
	cached, _, err := svc.Render(context.Background(), "acme", "t1", m.ID, opts, "")
	if err != nil {
		t.Fatalf("cached Render: %v", err)
	}
	if !bytes.Equal(cached, data) {
		t.Error("cached bytes differ from generated bytes")
	}
	if st.uploads != uploads {
		t.Error("cache hit must not upload")
	}
	if st.downloads != downloads+1 {
		t.Errorf("cache hit should download exactly the derivative, downloads went %d -> %d", downloads, st.downloads)
	}
}

func TestRender_FormatOverride(t *testing.T) {
	st := newFakeStorage()
	svc := newTestService(st)
	m := createMaster(t, svc, "acme", "t1")
	opts := imageprocessing.ResizeOptions{Width: 40, Height: 40, Mode: imageprocessing.ResizeModeExact}

	data, ct, err := svc.Render(context.Background(), "acme", "t1", m.ID, opts, "png")
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if ct != "image/png" {
		t.Errorf("content type = %s", ct)
	}
	if _, format, err := image.DecodeConfig(bytes.NewReader(data)); err != nil || format != "png" {
		t.Errorf("expected png payload, got %q err=%v", format, err)
	}
	if !st.has(derivativeKey("acme", "t1", m.ID, 40, 40, "exact", "png")) {
		t.Errorf("png derivative not cached; keys=%v", st.keys())
	}
}

