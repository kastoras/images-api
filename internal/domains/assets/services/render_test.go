func TestRender_TenantIsolation(t *testing.T) {
	svc := newTestService(newFakeStorage())
	m := createMaster(t, svc, "acme", "t1")
	opts := imageprocessing.ResizeOptions{Width: 10, Height: 10, Mode: imageprocessing.ResizeModeExact}

	for _, c := range [][2]string{{"acme", "t2"}, {"other", "t1"}} {
		if _, _, err := svc.Render(context.Background(), c[0], c[1], m.ID, opts, ""); !errors.Is(err, server.ErrNotFound) {
			t.Errorf("%v should not see acme/t1's master, got %v", c, err)
		}
	}
}

func TestRender_MasterDownloadFailure(t *testing.T) {
	st := newFakeStorage()
	svc := newTestService(st)
	m := createMaster(t, svc, "acme", "t1")
	boom := errors.New("boom")
	st.downloadErr[masterKey("acme", "t1", m.ID, extForFormat(m.Format))] = boom

	_, _, err := svc.Render(context.Background(), "acme", "t1", m.ID, imageprocessing.ResizeOptions{Width: 10, Height: 10, Mode: imageprocessing.ResizeModeExact}, "")
	if !errors.Is(err, boom) {
		t.Errorf("expected wrapped boom, got %v", err)
	}
}

func TestRender_CorruptMaster(t *testing.T) {
	st := newFakeStorage()
	svc := newTestService(st)
	hash := strings.Repeat("b", 64)
	st.put(masterKey("acme", "t1", hash, "jpg"), []byte("garbage"))

	_, _, err := svc.Render(context.Background(), "acme", "t1", hash, imageprocessing.ResizeOptions{Width: 10, Height: 10, Mode: imageprocessing.ResizeModeExact}, "")
	if err == nil || !strings.Contains(err.Error(), "decode master") {
		t.Errorf("expected decode master error, got %v", err)
	}
}

